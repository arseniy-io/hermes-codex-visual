const plural = (n, one, few, many) => {
  const value = Math.abs(Number(n))
  const last = value % 10
  const lastTwo = value % 100
  return last === 1 && lastTwo !== 11 ? one : last >= 2 && last <= 4 && (lastTwo < 12 || lastTwo > 14) ? few : many
}

