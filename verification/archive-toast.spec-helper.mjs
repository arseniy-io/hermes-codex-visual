import assert from 'node:assert/strict'

export async function verifyArchiveToast({ page, expect, sidebar, screenshot }) {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  const area = page.locator('[data-hcv-archive-toasts]')
  await expect(area).toHaveAttribute('data-hcv-archive-bridge', 'ready', { timeout: 20000 })
  const recent = sidebar.locator('[data-hcv-recents]')
  const recentToggle = recent.getByRole('button', { name: 'Недавние', exact: true })
  async function openRecents() {
    await expect(recentToggle).toBeVisible()
    if (await recentToggle.getAttribute('aria-expanded') !== 'true') await recentToggle.click()
  }
  await openRecents()
  const row = () => recent.getByRole('button', { name: 'Проверка каталога', exact: true })
    .locator('xpath=ancestor::div[contains(concat(" ", normalize-space(@class), " "), " row-hover ")][1]')
  async function choose(target, label) {
    await expect(target).toBeVisible()
    await target.locator('button[data-slot="row-button"]').click({ button: 'right' })
    await page.locator('[data-slot="context-menu-content"][data-state="open"]').getByRole('menuitem', { name: label, exact: true }).click()
  }
  const archive = target => target.getByRole('button', { name: 'Архивировать чат', exact: true })
  await row().hover()
  await archive(row()).click()
  const card = page.locator('[data-hcv-archive-toast]').first()
  await expect(card).toBeVisible()
  await expect(card.locator('[data-hcv-archive-label]')).toHaveText('Чат архивирован', { timeout: 15000 })
  await expect(row()).toHaveCount(0)
  await expect(card.getByRole('button', { name: 'Просмотр' })).toBeVisible()
  await expect(card.getByRole('button', { name: 'Отменить' })).toBeVisible()
  await expect(card.getByRole('button', { name: 'Закрыть' })).toBeVisible()
  await expect.poll(() => card.evaluate(node => node.getBoundingClientRect().top), { timeout: 3000 }).toBeGreaterThan(47.5)
  const styles = await card.evaluate(node => {
    const style = getComputedStyle(node); const r = node.getBoundingClientRect()
    const label = getComputedStyle(node.querySelector('[data-hcv-archive-label]'))
    const icon = getComputedStyle(node.querySelector('[data-hcv-archive-icon]'), '::before')
    return { height:r.height, top:r.top, font:style.fontFamily, size:style.fontSize, weight:label.fontWeight,
      transition:style.transitionDuration, radius:style.borderRadius, icon:icon.maskImage }
  })
  assert(Math.abs(styles.height - 42) < 0.1, `Unexpected toast height: ${styles.height}`)
  assert(Math.abs(styles.top - 48) < 0.5, `Unexpected toast position: ${styles.top}`)
  assert.equal(styles.size, '14px')
  assert.equal(styles.weight, '500')
  assert.equal(styles.radius, '12px')
  assert(styles.transition.includes('0.3s'))
  assert.notEqual(styles.icon, 'none')
  const view = card.getByRole('button', { name: 'Просмотр' })
  await expect(view).toHaveCSS('font-size', '12px')
  const idleBackground = await view.evaluate(node => getComputedStyle(node).backgroundColor)
  await view.hover()
  await expect.poll(() => view.evaluate(node => getComputedStyle(node).backgroundColor)).not.toBe(idleBackground)
  console.log('Archive toast measurements:', JSON.stringify({ ...styles, icon: 'confirmed' }))
  await screenshot('archive-toast.png')
  await card.getByRole('button', { name: 'Отменить' }).click()
  const restored = page.locator('[data-hcv-archive-toast][data-success]').first()
  await expect(restored).toContainText('Чат восстановлен', { timeout: 15000 })
  await restored.getByRole('button', { name:'Закрыть' }).click()
  await expect(restored).toHaveCount(0)
  await openRecents()
  await expect(row()).toBeVisible({ timeout: 15000 })
  await expect.poll(() => page.evaluate(async () => {
    const connectionId = window.__HERMES_PLUGIN_SDK__.host.state.connectionId.get()
    const data = await window.hermesDesktop.api({ connectionId, path: '/api/profiles/sessions?profile=default&limit=50&archived=only' })
    return data.sessions.some(session => session.id === '20261108_124502_aab002')
  }), { timeout: 15000 }).toBe(false)

  // A sidebar refresh can rebuild the Recent section after the stored row
  // comes back. Reopen it before starting the independent pinned-chat case.
  await openRecents()
  await choose(row(), 'Закрепить')
  const pinned = () => sidebar.locator('[data-sessions-mode="projects"] > [data-slot="sidebar-group"]')
    .getByRole('button', { name:'Проверка каталога', exact:true })
    .locator('xpath=ancestor::div[contains(concat(" ", normalize-space(@class), " "), " row-hover ")][1]')
  await archive(pinned()).press('Enter')
  const fast = page.locator('[data-hcv-archive-toast]').first()
  await expect(fast.getByRole('button', { name:'Отменить' })).toBeVisible()
  await fast.getByRole('button', { name:'Отменить' }).click()
  await expect(pinned()).toBeVisible({ timeout:15000 })
  const swipe = page.locator('[data-hcv-archive-toast][data-success]').first()
  await expect(swipe).toBeVisible()
  const box = await swipe.boundingBox()
  await page.mouse.move(box.x + 30, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + 95, box.y + box.height / 2, { steps:5 })
  await page.mouse.up()
  await expect(swipe).toHaveCount(0)
  await expect.poll(() => page.evaluate(async () => {
    const connectionId = window.__HERMES_PLUGIN_SDK__.host.state.connectionId.get()
    const data = await window.hermesDesktop.api({ connectionId, path:'/api/profiles/sessions?profile=default&limit=50&archived=include' })
    return Boolean(data.sessions.find(session => session.id === '20261108_124502_aab002')?.pinned)
  }), { timeout:15000 }).toBe(true)

  await page.emulateMedia({ reducedMotion:'reduce' })
  await choose(pinned(), 'В архив')
  const next = page.locator('[data-hcv-archive-toast]').first()
  await expect(next.locator('[data-hcv-archive-label]')).toHaveText('Чат архивирован', { timeout:15000 })
  const reducedDuration = await next.evaluate(node => parseFloat(getComputedStyle(node).transitionDuration))
  assert(reducedDuration <= .001, `Reduced-motion duration was ${reducedDuration}s`)
  await next.getByRole('button', { name: 'Просмотр' }).click()
  await expect.poll(() => page.evaluate(() => location.hash)).toContain('/settings?tab=sessions')
  console.log('Archive, undo, restored row, and archive navigation passed')
}
