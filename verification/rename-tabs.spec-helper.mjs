export async function verifyRenameTabs({ page, expect, projectChat, screenshot, prompts }) {
  const top = page.locator('[role="tab"][data-tree-tab="workspace"]:visible')
  const right = page.locator('[role="tab"][data-tree-tab="session-tile:20261108_124502_aab002"]:visible')
  const dialog = page.getByRole('dialog', { name: 'Переименовать чат', exact: true })
  const title = dialog.getByRole('textbox', { name: 'Название чата', exact: true })
  const save = dialog.getByRole('button', { name: 'Сохранить', exact: true })
  const nativeName = (id) => page.evaluate(async (sessionId) => (await window.hermesDesktop.api({
    connectionId: 'local', profile: 'default', path: '/api/sessions/' + sessionId,
  })).title, id)
  await expect(top).toContainText('Новый чат')
  await screenshot('new-chat.png')
  await top.click()
  await expect(dialog).toHaveCount(0)

  const projectName = page.locator('[data-hcv-project-name]').filter({ hasText: 'Тестовый проект' }).first()
  await projectName.dblclick()
  await expect(dialog).toHaveCount(0)
  await expect(projectName).toHaveText('Тестовый проект')
  if (!await projectChat('Ревью интерфейса').isVisible()) await projectName.click()

  await projectChat('Ревью интерфейса').click()
  await expect(top).toContainText('Ревью интерфейса')
  await expect(dialog).toHaveCount(0)

  // The sidebar's chat row opens the same form as a tab; it does not rename
  // its containing project and a single click remains ordinary navigation.
  const selectedRow = projectChat('Ревью интерфейса')
  await selectedRow.click({ button: 'right' })
  await expect(dialog).toHaveCount(0)
  const renameItem = page.getByRole('menuitem', { name: 'Переименовать', exact: true })
  await expect(renameItem).toBeVisible()
  expect(await page.getByRole('menuitem').count()).toBeGreaterThan(1)
  await renameItem.focus()
  await renameItem.press('Enter')
  await expect(dialog).toBeVisible()
  await expect(title).toHaveValue('Ревью интерфейса')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await selectedRow.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Закрепить', exact: true }).click()
  const pinned = page.locator('[data-sessions-mode] > [data-slot="sidebar-group"]').first()
  const pinnedRow = pinned.getByRole('button', { name: 'Ревью интерфейса', exact: true })
  await expect(pinnedRow).toBeVisible()
  await pinnedRow.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Открепить', exact: true }).click()
  await expect(pinnedRow).toHaveCount(0)
  await selectedRow.click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Переименовать', exact: true }).click()
  await expect(dialog).toBeVisible()
  await expect(title).toHaveValue('Ревью интерфейса')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await selectedRow.dblclick()
  await expect(dialog).toBeVisible()
  await expect(title).toBeFocused()
  await expect(title).toHaveValue('Ревью интерфейса')
  await expect.poll(() => title.evaluate(input => [input.selectionStart, input.selectionEnd])).toEqual([0, 16])
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(selectedRow).toBeFocused()
  await expect.poll(() => nativeName('20261108_124501_aab001')).toBe('Ревью интерфейса')

  // Double-click an initially different chat, persist its new title and
  // restore it for the independent right-tab checks below.
  const otherRow = projectChat('Проверка каталога')
  await otherRow.dblclick()
  await expect(dialog).toBeVisible()
  await expect(title).toHaveValue('Проверка каталога')
  await title.fill('Каталог после переименования')
  await save.click()
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => nativeName('20261108_124502_aab002')).toBe('Каталог после переименования')
  await expect(projectChat('Каталог после переименования')).toBeVisible()
  await projectChat('Каталог после переименования').click({ button: 'right' })
  await page.getByRole('menuitem', { name: 'Переименовать', exact: true }).click()
  await expect(dialog).toBeVisible()
  await expect(title).toHaveValue('Каталог после переименования')
  await title.fill('Каталог через меню')
  await save.click()
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => nativeName('20261108_124502_aab002')).toBe('Каталог через меню')
  await expect(projectChat('Каталог через меню')).toBeVisible()
  await projectChat('Каталог через меню').dblclick()
  await expect(title).toHaveValue('Каталог через меню')
  await title.fill('Проверка каталога')
  await title.press('Enter')
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => nativeName('20261108_124502_aab002')).toBe('Проверка каталога')
  await expect(projectChat('Проверка каталога')).toBeVisible()
  await projectChat('Ревью интерфейса').click()

  await top.dblclick()
  await expect(dialog).toBeVisible()
  await expect(dialog).toHaveCSS('width', '420px')
  const superellipse = await page.evaluate(() => CSS.supports('corner-shape', 'superellipse(1.5)'))
  await expect(dialog).toHaveCSS('border-radius', superellipse ? '20px' : '16px')
  await expect(title).toHaveCSS('border-radius', superellipse ? '10px' : '8px')
  await expect(save).toHaveCSS('border-radius', superellipse ? '12.5px' : '10px')
  await expect(dialog).toHaveCSS('color', 'rgb(223, 223, 223)')
  await expect(save).toHaveCSS('background-color', 'rgb(223, 223, 223)')
  await expect(dialog.locator('.hcv-rename-body')).toHaveCSS('padding', '20px')
  await expect(dialog.locator('[data-slot="dialog-title"]')).toHaveCSS('line-height', '28px')
  await expect(dialog.locator('[data-slot="dialog-description"]')).toHaveCSS('line-height', '21px')
  await expect(title).toBeFocused()
  await expect(title).toHaveValue('Ревью интерфейса')
  await expect.poll(() => title.evaluate(input => [input.selectionStart, input.selectionEnd])).toEqual([0, 16])
  await screenshot('codex-dialog.png')
  await screenshot('codex-dialog-detail.png', { clip: await dialog.boundingBox() })
  await title.fill('   ')
  await expect(save).toBeDisabled()
  await expect(title).toHaveAttribute('aria-invalid', 'true')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => nativeName('20261108_124501_aab001')).toBe('Ревью интерфейса')
  await top.dblclick()
  await expect(dialog).toBeVisible()
  await title.fill('Обзор дизайна')
  await save.click()
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => nativeName('20261108_124501_aab001')).toBe('Обзор дизайна')
  await expect(top).toContainText('Обзор дизайна')

  await expect(right).toBeVisible()
  await right.dblclick()
  await expect(dialog).toBeVisible()
  await expect(title).toHaveValue('Проверка каталога')
  await title.fill('Правая вкладка')
  await title.press('Enter')
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => nativeName('20261108_124502_aab002')).toBe('Правая вкладка')
  await expect(right).toContainText('Правая вкладка')
  await expect(top).toContainText('Обзор дизайна')
  await screenshot('right-renamed.png')

  const rightStrip = page.locator('[data-zone-tabstrip="grp-rename-right"]')
  await rightStrip.locator('button:has(> .codicon-add)').click()
  const newRight = rightStrip.locator('[data-tree-tab^="session-tile:"]:not([data-tree-tab="session-tile:20261108_124502_aab002"])')
  await expect(newRight).toContainText('Новый чат')
  await newRight.dblclick()
  await expect(dialog).toBeVisible()
  await expect(title).toHaveValue('')
  await title.fill('Новый справа')
  await save.click()
  await expect(dialog).toHaveCount(0, { timeout: 15000 })
  await expect(newRight).toContainText('Новый справа')
  const newId = (await newRight.getAttribute('data-tree-tab')).slice('session-tile:'.length)
  await expect.poll(() => nativeName(newId)).toBe('Новый справа')

  await page.locator('[data-tour="sidebar-nav-new-session"]').locator('xpath=ancestor::button[1]').click()
  await expect(top).toContainText('Новый чат')
  const mainChat = page.locator('[data-chat-surface][data-composer-target="main"]:visible')
  const draft = mainChat.locator('[data-slot="composer-rich-input"]')
  const attachment = mainChat.locator('[data-slot="composer-attachments"]')
  const attachmentIdentity = () => attachment.evaluate(element => {
    const key = Object.keys(element).find(name => name.startsWith('__reactFiber$'))
    for (let node = key && element[key]; node; node = node.return) {
      const items = node.memoizedProps?.attachments
      if (Array.isArray(items)) return items.map(({ id, label, kind, path }) => ({ id, label, kind, path }))
    }
    return null
  })
  await draft.evaluate(async editor => {
    const canvas = document.createElement('canvas')
    canvas.width = 2
    canvas.height = 2
    const png = await new Promise(resolve => canvas.toBlob(resolve, 'image/png'))
    const clipboardData = new DataTransfer()
    clipboardData.items.add(new File([png], 'rename-draft.png', { type: 'image/png' }))
    editor.dispatchEvent(new ClipboardEvent('paste', { bubbles: true, cancelable: true, clipboardData }))
  })
  await expect(attachment).toContainText('rename-draft')
  const originalAttachment = await attachmentIdentity()
  expect(originalAttachment).toHaveLength(1)
  expect(originalAttachment[0].id).toBeTruthy()
  await draft.click()
  await page.keyboard.insertText('Текст черновика для проверки')
  await expect(draft).toHaveText('Текст черновика для проверки')
  await top.dblclick()
  await expect(dialog).toBeVisible()
  await title.fill('Новый проектный разговор')
  await title.press('Enter')
  await expect(dialog).toHaveCount(0, { timeout: 15000 })
  await expect(top).toContainText('Новый проектный разговор')
  await expect(draft).toHaveText('Текст черновика для проверки')
  await expect(attachment).toContainText('rename-draft')
  await expect.poll(attachmentIdentity).toEqual(originalAttachment)
  const renamedRoute = await page.evaluate(() => location.hash)
  await projectChat('Обзор дизайна').click()
  await expect(top).toContainText('Обзор дизайна')
  expect(await page.evaluate(() => location.hash)).not.toBe(renamedRoute)
  await page.evaluate(route => { location.hash = route }, renamedRoute)
  await expect(top).toContainText('Новый проектный разговор')
  await expect(draft).toHaveText('Текст черновика для проверки')
  await expect(attachment).toContainText('rename-draft')
  await expect.poll(attachmentIdentity).toEqual(originalAttachment)
  expect(prompts).toHaveLength(0)
}
