export async function verifyRenameTabs({ page, expect, projectChat, screenshot, prompts }) {
  const top = page.locator('[role="tab"][data-tree-tab="workspace"]:visible')
  const right = page.locator('[role="tab"][data-tree-tab="session-tile:20261108_124502_aab002"]:visible')
  const dialog = page.getByRole('dialog', { name: 'Переименовать чат', exact: true })
  const title = dialog.getByRole('textbox', { name: 'Название чата', exact: true })
  const save = dialog.getByRole('button', { name: 'Сохранить', exact: true })
  const nativeName = (id) => page.evaluate(async (sessionId) => (await window.hermesDesktop.api({
    connectionId: 'local', profile: 'default', path: '/api/sessions/' + sessionId,
  })).title, id)
  await expect(top).toContainText('Новый чат')
  await screenshot('new-chat.png')
  await top.click()
  await expect(dialog).toHaveCount(0)

  await projectChat('Ревью интерфейса').click()
  await expect(top).toContainText('Ревью интерфейса')
  await top.dblclick()
  await expect(dialog).toBeVisible()
  await expect(dialog).toHaveCSS('width', '420px')
  await expect(dialog).toHaveCSS('border-radius', '16px')
  await expect(dialog.locator('.hcv-rename-body')).toHaveCSS('padding', '20px')
  await expect(title).toBeFocused()
  await expect(title).toHaveValue('Ревью интерфейса')
  await expect.poll(() => title.evaluate(input => [input.selectionStart, input.selectionEnd])).toEqual([0, 16])
  await screenshot('codex-dialog.png')
  await screenshot('codex-dialog-detail.png', { clip: await dialog.boundingBox() })
  await title.fill('   ')
  await expect(save).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => nativeName('20261108_124501_aab001')).toBe('Ревью интерфейса')
  await top.dblclick()
  await expect(dialog).toBeVisible()
  await title.fill('Обзор дизайна')
  await save.click()
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => nativeName('20261108_124501_aab001')).toBe('Обзор дизайна')
  await expect(top).toContainText('Обзор дизайна')

  await expect(right).toBeVisible()
  await right.dblclick()
  await expect(dialog).toBeVisible()
  await expect(title).toHaveValue('Проверка каталога')
  await title.fill('Правая вкладка')
  await title.press('Enter')
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => nativeName('20261108_124502_aab002')).toBe('Правая вкладка')
  await expect(right).toContainText('Правая вкладка')
  await expect(top).toContainText('Обзор дизайна')
  await screenshot('right-renamed.png')

  const rightStrip = page.locator('[data-zone-tabstrip="grp-rename-right"]')
  await rightStrip.locator('button:has(> .codicon-add)').click()
  const newRight = rightStrip.locator('[data-tree-tab^="session-tile:"]:not([data-tree-tab="session-tile:20261108_124502_aab002"])')
  await expect(newRight).toContainText('Новый чат')
  await newRight.dblclick()
  await expect(dialog).toBeVisible()
  await expect(title).toHaveValue('')
  await title.fill('Новый справа')
  await save.click()
  await expect(dialog).toHaveCount(0, { timeout: 15000 })
  await expect(newRight).toContainText('Новый справа')
  const newId = (await newRight.getAttribute('data-tree-tab')).slice('session-tile:'.length)
  await expect.poll(() => nativeName(newId)).toBe('Новый справа')

  await page.locator('[data-tour="sidebar-nav-new-session"]').locator('xpath=ancestor::button[1]').click()
  await expect(top).toContainText('Новый чат')
  const mainChat = page.locator('[data-chat-surface][data-composer-target="main"]:visible')
  const draft = mainChat.locator('[data-slot="composer-rich-input"]')
  const attachment = mainChat.locator('[data-slot="composer-attachments"]')
  await draft.evaluate(async editor => {
    const canvas = document.createElement('canvas')
    canvas.width = 2
    canvas.height = 2
    const png = await new Promise(resolve => canvas.toBlob(resolve, 'image/png'))
    const clipboardData = new DataTransfer()
    clipboardData.items.add(new File([png], 'rename-draft.png', { type: 'image/png' }))
    editor.dispatchEvent(new ClipboardEvent('paste', { bubbles: true, cancelable: true, clipboardData }))
  })
  await expect(attachment).toContainText('rename-draft')
  await draft.click()
  await page.keyboard.insertText('Текст черновика для проверки')
  await expect(draft).toHaveText('Текст черновика для проверки')
  await top.dblclick()
  await expect(dialog).toBeVisible()
  await title.fill('Новый проектный разговор')
  await title.press('Enter')
  await expect(dialog).toHaveCount(0, { timeout: 15000 })
  await expect(top).toContainText('Новый проектный разговор')
  await expect(draft).toHaveText('Текст черновика для проверки')
  await expect(attachment).toContainText('rename-draft')
  expect(prompts).toHaveLength(0)
}
