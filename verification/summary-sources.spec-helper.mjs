export async function verifySummarySources({ page, expect, projectChat, screenshot }) {
  await projectChat('Проверка каталога').click()
  const summary = page.locator('[data-hcv-context-card]')
  const compact = summary.locator('[data-hcv-sources-compact]')
  const heading = compact.getByRole('button', { name: /^Источники(?: \d+)?$/ })
  const list = compact.getByRole('list', { name: 'Источники' })
  const viewAll = compact.getByRole('button', { name: 'Показать все' })
  const plus = compact.getByRole('button', { name: 'Добавить источник' })
  const addMenu = page.locator('[data-hcv-sources-add-menu]')

  await expect(list.getByRole('listitem')).toHaveCount(3)
  await expect(list.locator('.hcv-source-row').first()).toHaveCSS('min-block-size', '28px')
  const thumbnail = list.locator('img').first()
  await expect(thumbnail).toHaveCSS('width', '18px')
  await expect(thumbnail).toHaveCSS('border-radius', '3px')
  await expect.poll(() => thumbnail.evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true)
  await screenshot('sources-compact.png')

  await heading.click()
  await expect(heading).toHaveAttribute('aria-expanded', 'false')
  await expect(compact.locator('.hcv-sources-disclosure')).toHaveAttribute('inert', '')
  await heading.click()
  await expect(heading).toHaveAttribute('aria-expanded', 'true')
  await expect(viewAll).toBeVisible()

  await summary.getByRole('button', { name: 'Действия со сводкой' }).click()
  await page.getByRole('menuitem', { name: 'Открепить сводку' }).click()
  await expect(summary).toHaveAttribute('data-pinned', 'false')
  await plus.click()
  await expect(addMenu).toBeVisible()
  await expect(addMenu.getByRole('menuitem', { name: 'Использовать плагины' })).toBeVisible()
  await screenshot('sources-add.png')
  await addMenu.getByRole('menuitem', { name: 'Прикрепить файлы или папки' }).click()
  const nativeAdd = page.locator('[data-chat-surface][data-composer-target="main"] button[aria-haspopup="menu"]:has(> .codicon-add)')
  await expect(nativeAdd).toHaveAttribute('aria-expanded', 'true')
  await expect(page.getByRole('menuitem', { name: 'Файлы…', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(nativeAdd).toHaveAttribute('aria-expanded', 'false')

  await thumbnail.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)

  await viewAll.click()
  const pane = page.locator('[data-hcv-sources-pane]:visible')
  await expect(pane).toBeVisible()
  const attachment = pane.getByRole('listitem').filter({ hasText: 'fixture-rules.txt' })
  await expect(attachment.getByText('Прикреплено к разговору', { exact: true })).toBeVisible()
  await expect(attachment).toHaveCSS('padding-block', '16px')
  await expect(pane.getByText('https://example.invalid/connector-guide', { exact: true })).toBeVisible()
  await expect(pane.getByRole('button', { name: 'Тестовый поиск', exact: true })).toBeVisible({ timeout: 15000 })
  await screenshot('sources-pane.png')

  const tab = page.locator('[data-tree-tab="plugin-workspace:hermes-codex-visual-summary-sources"]')
  const strip = page.locator('[data-zone-tabstrip]').filter({ has: tab })
  await strip.getByRole('button', { name: 'Добавить вкладку', exact: true }).click()
  const picker = page.locator('[data-hcv-summary-picker]')
  await expect(picker.getByRole('menuitem', { name: 'Субагенты', exact: true })).toBeVisible()
  await picker.getByRole('menuitem', { name: 'Изменения', exact: true }).click()
  const changes = strip.locator('[data-tree-tab="plugin-workspace:hermes-codex-visual-summary-changes"]')
  await expect(changes).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('[data-hcv-changes-pane]:visible')).toBeVisible()
  await tab.click()
  await expect(tab).toHaveAttribute('aria-selected', 'true')
  await changes.hover()
  await changes.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await expect(changes).toHaveCount(0)
  await expect(pane).toBeVisible()

  await pane.getByRole('button', { name: 'fixture-note.md', exact: true }).click()
  await expect(page.locator('[data-slot="aui_thread-content"]').getByRole('button', { name: 'Скрыть', exact: true })).toBeVisible()
}
