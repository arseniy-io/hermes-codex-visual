import assert from 'node:assert/strict'

export async function verifySidebarActivity({
  page, expect, sidebar, screenshot, projectChat, newChat, waitForChatReady, mock, prompt, releaseFirstToken,
}) {
  const section = sidebar.locator('[data-hcv-projects-section]')
  const heading = section.locator('[data-hcv-projects-header]')
  const projects = heading.getByRole('button', { name: 'Проекты', exact: true })
  const filter = heading.getByRole('button', { name: 'Фильтры', exact: true })
  const recents = sidebar.locator('[data-hcv-recents]')
  const recent = recents.getByRole('button', { name: 'Недавние', exact: true })
  const caret = toggle => toggle.locator('[data-hcv-icon="sidebarDisclosure"]')
  const status = (row, kind) => row.locator(`:scope > [data-hcv-project-status="${kind}"]:not([hidden])`)
  const spinner = row => status(row, 'working')
  const markAll = heading.locator('button:has(> .codicon-check-all)')
  const away = () => page.mouse.move(700, 110)
  async function clickFarEdge(button, action) {
    const box = await button.boundingBox()
    const trailing = await action.boundingBox()
    assert(box.width > 95 && Math.abs(box.x + box.width - trailing.x) < 3, 'Heading fills the free space up to its controls')
    await button.click({ position: { x: box.width - 2, y: box.height / 2 } })
  }
  const project = section.getByRole('button', { name: 'Тестовый проект', exact: true })
  const projectRow = project.locator('xpath=ancestor::*[@data-hcv-project-row][1]')
  const chat = projectChat('Ревью интерфейса')
  const chatRow = chat.locator('xpath=..')
  const recentMore = recents.getByRole('button', { name: 'Действия с недавними', exact: true })

  await expect(newChat).toHaveAccessibleName('Новый чат')
  await expect(newChat.locator('[data-slot="kbd-group"]')).toBeHidden()
  await expect(projects).toHaveAttribute('aria-expanded', 'true')
  await away()
  await expect(caret(projects)).toHaveCSS('opacity', '0')
  await project.hover()
  await expect(caret(projects)).toHaveCSS('opacity', '1')
  await expect(filter).toHaveCSS('opacity', '0')
  const bounds = await section.boundingBox()
  const row = await projectRow.boundingBox()
  await page.mouse.move(bounds.x + bounds.width + 2, row.y + row.height / 2)
  await expect(caret(projects)).toHaveCSS('opacity', '0')
  await project.hover()
  await expect(caret(projects)).toHaveCSS('opacity', '1')
  await page.mouse.move(bounds.x - 2, row.y + row.height / 2)
  await expect(caret(projects)).toHaveCSS('opacity', '0')
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height + 3)
  await expect(caret(projects)).toHaveCSS('opacity', '0')
  await clickFarEdge(projects, filter)
  await expect(projects).toHaveAttribute('aria-expanded', 'false')
  await away()
  await expect(caret(projects)).toHaveCSS('opacity', '1')
  await clickFarEdge(projects, filter)
  await expect(projects).toHaveAttribute('aria-expanded', 'true')
  await clickFarEdge(recent, recentMore)
  await expect(recent).toHaveAttribute('aria-expanded', 'true')
  await clickFarEdge(recent, recentMore)
  await expect(recent).toHaveAttribute('aria-expanded', 'false')

  // The native palette normally enters the drill-in. Its project action
  // should reveal the same folder inline each time, even from a folded list.
  for (let attempt = 0; attempt < 2; attempt++) {
    await clickFarEdge(projects, filter)
    await expect(projects).toHaveAttribute('aria-expanded', 'false')
    await page.keyboard.press('Control+k')
    const palette = page.getByRole('dialog').filter({ has: page.locator('[data-slot="command-input"]') })
    const input = palette.locator('[data-slot="command-input"]')
    await input.fill('Тестовый проект')
    const options = palette.getByRole('option')
    const target = options.filter({
      has: page.getByText('Тестовый проект', { exact: true }),
    })
    await expect(target).toBeVisible()
    for (let i = 0, count = await options.count(); i < count; i++) {
      if (await target.getAttribute('aria-selected') === 'true') break
      await input.press('ArrowDown')
    }
    await expect(target).toHaveAttribute('aria-selected', 'true')
    await input.press('Enter')
    await expect(palette).toHaveCount(0)
    await expect(projects).toHaveAttribute('aria-expanded', 'true')
    await expect(project).toHaveAttribute('aria-expanded', 'true')
    await expect(chat).toBeVisible()
    await expect(sidebar.locator('[data-sessions-mode="project"]')).toHaveCount(0)
    await expect(sidebar.getByText('Все проекты', { exact: true })).toHaveCount(0)
    await expect(sidebar.getByText(/^(На прошлой неделе|Ранее в этом месяце)$/i)).toHaveCount(0)
    await project.click()
    await expect(project).toHaveAttribute('aria-expanded', 'false')
  }
  await project.click()
  const other = projectChat('Проверка каталога').locator('xpath=..')
  const age = other.locator('time[datetime]')
  await expect(age).toHaveText('5д')
  await expect(age).toBeHidden()
  await other.hover()
  await other.locator('button[aria-haspopup="menu"]:has(> .codicon-kebab-vertical)').click()
  await page.getByRole('menuitem', { name: 'Отметить как непрочитанное', exact: true }).click()
  await expect(other.getByRole('status', { name: /не прочитан/ })).toBeAttached()
  await projects.hover()
  await expect(status(heading, 'unread')).toHaveCount(0)
  await expect(markAll).toBeHidden()

  await chat.click()
  const composer = await waitForChatReady(page, 10000)
  await clickFarEdge(projects, filter)
  await expect(chat).toHaveCount(0)
  await expect(status(heading, 'unread')).toBeVisible()
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await composer.fill(prompt)
  await composer.press('Enter')
  await expect(spinner(heading)).toBeVisible()
  await expect(markAll).toBeHidden()
  await expect(status(heading, 'unread')).toHaveCount(0)

  const loading = page.locator('[data-slot="aui_response-loading"]')
  const thinking = loading.locator('[data-hcv-thinking]')
  const sweep = thinking.locator('[data-hcv-thinking-sweep]')
  const counter = loading.locator(':scope > [aria-hidden="true"]:not(.dither)')
  await expect(thinking).toHaveText('Думаю')
  await expect(loading.locator(':scope > .dither')).toBeHidden()
  await expect(sweep).toHaveCSS('animation-name', 'hcv-thinking-sweep')
  await expect(sweep).toHaveCSS('animation-duration', '4s')
  await expect(sweep).toHaveCSS('animation-delay', '0.6s')
  await expect.poll(() => sweep.evaluate(node => node.getAnimations()[0]?.effect.getKeyframes()[0]?.easing)).toBe('steps(48)')
  const startSeconds = Number.parseInt(await counter.textContent(), 10)
  await expect.poll(async () => Number.parseInt(await counter.textContent(), 10)).toBeGreaterThanOrEqual(Math.max(2, startSeconds + 1))
  await expect(counter).toHaveText(/^\d+s$/)
  await screenshot('thinking-and-timer.png')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(sweep).toHaveCSS('animation-name', 'none')
  await expect(thinking).toBeVisible()
  const shownSeconds = Number.parseInt(await counter.textContent(), 10)
  releaseFirstToken()
  await mock.waitForHeldStream()
  const live = page.locator('[data-hcv-live-turn]')
  await expect(live.locator('[data-hcv-thinking]')).toHaveText('Думаю')
  await expect.poll(async () => Number.parseInt(await live.locator('[data-hcv-live-time]').textContent(), 10))
    .toBeGreaterThanOrEqual(shownSeconds)
  await clickFarEdge(projects, filter)
  await expect(chatRow).toHaveAttribute('data-working', 'true')
  await expect(chatRow.locator('time[datetime]')).toHaveText('сейчас')
  await expect(chatRow.locator('time[datetime]')).toBeHidden()
  await expect(markAll).toBeHidden()
  await expect(status(projectRow, 'unread')).toHaveCount(0)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await expect.poll(() => chatRow.evaluate(node => getComputedStyle(node, '::after').width)).toBe('14px')
  await expect.poll(() => chatRow.evaluate(node => getComputedStyle(node, '::after').animationDuration)).toBe('2s')
  await expect.poll(() => chatRow.evaluate(node => getComputedStyle(node, '::after').animationTimingFunction)).toBe('steps(60)')
  await expect(spinner(projectRow)).toBeHidden()
  await away()
  await screenshot('sidebar-working-chat.png')

  await project.click()
  await expect(chat).toHaveCount(0)
  await away()
  await expect(spinner(projectRow)).toBeVisible()
  const inactive = section.locator('[data-hcv-project-row]').filter({ hasText: /^Сайт$/ })
  await expect(spinner(inactive)).toBeHidden()
  await page.keyboard.press('Control+n')
  await expect(page.locator('[data-slot="aui_thread-viewport"]').getByText(prompt, { exact: true })).toHaveCount(0)
  await expect(spinner(projectRow)).toBeVisible()
  await screenshot('sidebar-working-project.png')

  await clickFarEdge(projects, filter)
  await expect(project).toHaveCount(0)
  await expect(spinner(heading)).toBeVisible()
  await expect(markAll).toBeHidden()
  await screenshot('sidebar-working-projects-folded.png')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect.poll(() => spinner(heading).evaluate(node => getComputedStyle(node, '::before').animationName)).toBe('none')
  mock.releaseHeldStream()
  await expect(spinner(heading)).toBeHidden({ timeout: 15000 })
  await expect(markAll).toBeVisible()
  await expect.poll(() => markAll.evaluate(node => getComputedStyle(node, '::after').backgroundColor)).toBe('rgb(51, 156, 245)')
  await screenshot('sidebar-unread-folded.png')
  await clickFarEdge(projects, filter)
  await expect(markAll).toBeHidden()
  await away()
  await expect(status(projectRow, 'unread')).toBeVisible()
  await clickFarEdge(projects, filter)
  await expect(markAll).toBeVisible()
  await markAll.click()
  await expect(markAll).toHaveCount(0)
  await clickFarEdge(projects, filter)
  if (await project.getAttribute('aria-expanded') === 'false') await project.click()
  await projectChat('Проверка каталога').click()
  await expect(other.getByRole('status', { name: /не прочитан/ })).toHaveCount(0)
  await chat.click()
  await expect(chatRow.getByRole('status', { name: /не прочитан/ })).toHaveCount(0)
  await clickFarEdge(projects, filter)
  await expect(status(heading, 'unread')).toHaveCount(0)

  const emptyProfile = sidebar.locator('[data-slot="profile-rail"]').getByRole('button', { name: 'visual-other', exact: true })
  await emptyProfile.click()
  await expect(emptyProfile).toHaveAttribute('aria-pressed', 'true', { timeout: 30000 })
  await expect(page.getByRole('button', { name: 'Шлюз готов', exact: true })).toBeVisible({ timeout: 30000 })
  await expect(projects).toHaveAccessibleName('Проекты')
  if (await projects.getAttribute('aria-expanded') === 'false') await clickFarEdge(projects, filter)
  await expect(section.locator('[data-hcv-project-name]').filter({ hasText: /^Пустой проект$/ })).toBeVisible()
  await expect(recent).toHaveAttribute('aria-expanded', 'false')
  await clickFarEdge(recent, recentMore)
  const empty = recents.getByText('Нет чатов', { exact: true })
  await expect(empty).toBeVisible()
  await away()
  await expect(caret(recent)).toHaveCSS('opacity', '0')
  await empty.hover({ position: { x: 12, y: 10 } })
  await expect(caret(recent)).toHaveCSS('opacity', '1')
  await expect(caret(recent)).not.toHaveCSS('mask-image', 'none')
  await expect(caret(recent)).toHaveCSS('width', '12px')
  await away()
  await expect(caret(recent)).toHaveCSS('opacity', '0')
  await screenshot('sidebar-recent-empty.png')
  console.log(JSON.stringify({
    farEdge: true, sectionHover: true, emptyHover: true, nativeShortcut: true, workingLevels: 3,
    reducedMotion: true, hiddenAges: true, unreadPriority: true, thinkingTimer: true, inlineProjectNavigation: true,
  }))
}

export async function verifyProjectReveal({ page, expect, sidebar, screenshot }) {
  const profileRail = sidebar.locator('[data-slot="profile-rail"]')
  await profileRail.getByRole('button', { name: 'Показать все профили', exact: true }).click()
  const allProfiles = profileRail.getByRole('button', { name: 'Переключиться на default', exact: true })
  await expect(allProfiles).toBeVisible()

  const filter = sidebar.getByRole('button', { name: 'Фильтры', exact: true })
  const grouping = page.getByRole('menuitem', { name: /^Группировка/ })
  async function chooseUpdated() {
    await filter.click()
    await grouping.press('ArrowRight')
    await page.getByRole('menuitemradio', { name: 'Обновление', exact: true }).click()
    for (let i = 0; i < 2 && await page.locator('[role="menu"][data-state="open"]').count(); i++) {
      await page.keyboard.press('Escape')
    }
    await expect(grouping).toHaveCount(0)
  }
  await chooseUpdated()

  const flat = sidebar.locator('[data-sessions-mode="flat"]')
  const openProjects = flat.locator('[data-hcv-show-projects]')
  await expect(openProjects).toHaveCSS('height', '28px')
  const flatRecent = flat.getByRole('button', { name: 'Недавние', exact: true })
  const flatRecentContent = flatRecent.locator('xpath=ancestor::*[@data-slot="sidebar-group"][1]')
    .locator(':scope > [data-slot="sidebar-group-content"]')
  if (!await flatRecentContent.count()) await flatRecent.click()
  await expect(flat.getByRole('button', { name: 'Ревью интерфейса', exact: true })).toBeVisible()

  const tree = sidebar.locator('[data-sessions-mode="projects"]')
  const projectHeading = tree.locator('[data-hcv-projects-header] [data-hcv-section-toggle]')
  const treeRecent = tree.locator('[data-hcv-recents-toggle]')
  await openProjects.click()
  await expect(grouping, 'The Projects heading must not open the grouping menu').toHaveCount(0)
  await expect(projectHeading).toHaveAttribute('aria-expanded', 'true')
  await expect(treeRecent).toHaveAttribute('aria-expanded', 'true')
  await expect(tree.locator('[data-hcv-recents-list]').getByRole('button', { name: 'Ревью интерфейса', exact: true })).toBeVisible()
  await expect(allProfiles).toBeVisible()

  const project = tree.getByRole('button', { name: 'Тестовый проект', exact: true })
  await expect(project).toBeVisible()
  if (await project.getAttribute('aria-expanded') === 'true') await project.click()
  await project.click()
  await expect(project).toHaveAttribute('aria-expanded', 'true')
  await expect(grouping).toHaveCount(0)
  await screenshot('projects-direct-open.png')

  await projectHeading.click()
  await expect(projectHeading).toHaveAttribute('aria-expanded', 'false')
  await expect(treeRecent).toHaveAttribute('aria-expanded', 'true')
  await chooseUpdated()
  await expect(flatRecent).toBeVisible()
  await expect(flatRecentContent).toHaveCount(0)
  await expect(openProjects).toHaveAccessibleName('Проекты')
  await openProjects.press('Enter')
  await expect(projectHeading).toHaveAttribute('aria-expanded', 'true')
  await expect(projectHeading).toBeFocused()
  await expect(treeRecent).toHaveAttribute('aria-expanded', 'false')
  await expect(grouping).toHaveCount(0)
  await filter.click()
  await expect(grouping).toContainText('Проект')
  await page.keyboard.press('Escape')
  await expect(grouping).toHaveCount(0)
  console.log(JSON.stringify({ allProfiles: true, directProjects: true, inlineProject: true, recentState: true, keyboard: true, filterMenu: true }))
}

export async function verifySidebarSelection({ page, expect, navigation, screenshot, openThemeSettings, closeSettings }) {
  const artifacts = navigation('artifacts')
  const messaging = navigation('messaging')
  const nav = artifacts.locator('xpath=ancestor::*[@data-slot="sidebar-menu"][1]')
  const fill = 'rgb(41, 41, 41)'
  await artifacts.click()
  await expect(page).toHaveURL(/\/artifacts(?:[/?#]|$)/)
  await page.mouse.move(670, 130)
  await expect(artifacts).toHaveCSS('background-color', fill)

  if (process.env.HERMES_VISUAL_SIDEBAR_SELECTION_BEFORE === '1') {
    await expect(artifacts).toHaveCSS('border-top-width', '1px')
    await expect(artifacts).toHaveCSS('border-top-color', 'rgb(57, 57, 57)')
    await screenshot('selected.png', { clip: await nav.boundingBox() })
    return
  }

  const shaped = await page.evaluate(() => CSS.supports('corner-shape', 'superellipse(1.5)'))
  for (const id of ['new-session', 'capabilities', 'messaging', 'artifacts', 'cron']) {
    await expect(navigation(id)).toHaveCSS('border-top-width', '0px')
    await expect(navigation(id)).toHaveCSS('border-radius', shaped ? '12.5px' : '10px')
  }
  await expect(artifacts).toHaveCSS('outline-style', 'none')
  await screenshot('selected.png', { clip: await nav.boundingBox() })

  await messaging.hover()
  await expect(messaging).toHaveCSS('background-color', fill)
  await expect(artifacts).toHaveCSS('background-color', fill)
  await page.mouse.down()
  await expect(messaging).toHaveCSS('border-top-width', '0px')
  await expect(messaging).toHaveCSS('background-color', fill)
  await page.mouse.up()
  await expect(page).toHaveURL(/\/messaging(?:[/?#]|$)/)
  await page.mouse.move(670, 130)
  await expect(artifacts).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await expect(messaging).toHaveCSS('background-color', fill)

  await messaging.focus()
  await page.keyboard.press('Tab')
  await expect(artifacts.and(page.locator(':focus-visible'))).toBeFocused()
  await expect(artifacts).toHaveCSS('border-top-width', '0px')
  await expect(artifacts).toHaveCSS('outline-style', 'solid')
  await expect(artifacts).toHaveCSS('outline-width', '2px')
  await expect(artifacts).toHaveCSS('outline-offset', '-2px')
  await expect(artifacts).toHaveCSS('outline-color', 'rgba(51, 156, 255, 0.7)')
  await screenshot('keyboard.png', { clip: await nav.boundingBox() })
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/artifacts(?:[/?#]|$)/)

  await openThemeSettings()
  await page.getByText(/^(Светлая|Light)$/, { exact: true }).first().click()
  await expect(page.locator('html')).toHaveAttribute('data-hermes-mode', 'light')
  await closeSettings()
  await artifacts.click()
  await page.mouse.move(670, 130)
  await expect(artifacts).toHaveCSS('border-top-width', '0px')
  await expect(artifacts).toHaveCSS('background-color', 'rgb(229, 229, 229)')
  await screenshot('light.png', { clip: await nav.boundingBox() })
}

