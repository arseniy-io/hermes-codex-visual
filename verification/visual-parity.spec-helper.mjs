const gatewayId = (field) => `[id="setting-field-gateway.${field}"]`
const projectMenu = '[data-hcv-draft-menu="projects"]:popover-open'
const profileName = 'visual-audit-helper-with-long-name'

const paint = (node) => node.evaluate((element) => {
  const s = getComputedStyle(element)
  return {
    radius: s.borderRadius,
    border: s.borderBottomWidth,
    borderColor: s.borderBottomColor,
    background: s.backgroundColor,
    shadow: s.boxShadow,
    outline: s.outlineStyle,
    decoration: s.textDecorationLine,
    font: s.fontFamily,
    size: s.fontSize,
    height: element.getBoundingClientRect().height,
  }
})

export async function verifyVisualParity({ page, expect, screenshot, navigation, openThemeSettings, closeSettings }) {
  const before = process.env.HERMES_VISUAL_PARITY_BEFORE === '1'
  const seen = {}
  const go = (route) => page.evaluate(value => { location.hash = '#/' + value }, route)
  const settings = page.locator('[data-overlay-surface]:visible main')
  const cards = settings.locator(gatewayId('connection-mode') + ' > div > button')
  const logs = settings.locator(gatewayId('diagnostics')).getByRole('button')
  const keychain = settings.locator(gatewayId('keychain-encryption')).getByRole('switch')
  await go('settings?tab=gateway&page=connection')
  await expect(cards).toHaveCount(4)
  await expect(cards.first()).toBeVisible()
  await expect(keychain).toBeVisible()
  const selected = cards.filter({ has: page.locator('svg.tabler-icon-check') })
  await expect(selected).toHaveCount(1)
  seen.gateway = { selected: await paint(selected), action: await paint(logs), toggle: await paint(keychain) }
  await screenshot('gateway-dark.png')
  if (!before) {
    await expect(settings).toHaveCSS('max-inline-size', '768px')
    await expect(cards.first().locator('xpath=..')).toHaveCSS('border-radius', '16px')
    await expect(selected).toHaveCSS('box-shadow', 'none')
    await expect(logs).toHaveCSS('text-decoration-line', 'none')
    await expect(logs).toHaveCSS('min-block-size', '28px')
    await expect(keychain).toHaveCSS('block-size', '20px')
    const remote = cards.nth(2)
    const idle = await paint(remote)
    await remote.hover()
    await expect.poll(async () => (await paint(remote)).background).not.toBe(idle.background)
    await remote.press('Enter')
    await expect(remote.locator('svg.tabler-icon-check')).toBeVisible()
    const url = settings.locator('input[data-slot="input"]:visible').first()
    await expect(url).toBeEditable()
    await url.focus()
    await expect(url).toHaveCSS('box-shadow', 'none')
    await expect(url).toHaveCSS('outline-width', '2px')
    await cards.first().press('Enter')
    await expect(cards.first().locator('svg.tabler-icon-check')).toBeVisible()
    await expect(url).toHaveCount(0)
    await page.emulateMedia({ forcedColors: 'active' })
    await expect(cards.first()).toBeFocused()
    await expect(cards.first()).toHaveCSS('outline-width', '2px')
    await page.emulateMedia({ forcedColors: 'none' })
  }

  await go('')
  await navigation('new-session').click()
  const composer = page.locator('[data-chat-surface][data-composer-target="main"]:visible [data-slot="composer-surface"]')
  const draft = page.locator('[data-hcv-draft-bar]:visible')
  const project = draft.getByRole('button', { name: 'Выбрать проект', exact: true })
  await project.click()
  const menu = page.locator(projectMenu)
  const search = menu.getByRole('searchbox', { name: 'Поиск проектов' })
  const searchRow = menu.locator('[data-hcv-draft-search-row]')
  await expect(search).toBeFocused()
  await expect(menu.getByRole('button', { name: 'Сайт', exact: true })).toBeVisible()
  seen.composer = { surface: await paint(composer), strip: await paint(draft), menu: await paint(menu), search: await paint(searchRow) }
  await screenshot('project-menu-dark.png')
  if (!before) {
    await expect(composer).toHaveCSS('border-width', '0px')
    await expect(composer).toHaveCSS('background-color', 'rgb(54, 54, 54)')
    await expect(composer).toHaveCSS('height', '98px')
    await expect(menu).toHaveCSS('width', '260px')
    await expect(menu).toHaveCSS('border-radius', /^(16|20)px$/)
    await expect(menu).toHaveCSS('background-color', 'rgb(45, 45, 45)')
    await expect(menu).toHaveCSS('backdrop-filter', 'none')
    await expect(searchRow).toHaveCSS('border-bottom-width', '0px')
    await expect(searchRow).toHaveCSS('box-shadow', 'none')
    await expect(searchRow).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
    await expect(searchRow).toHaveCSS('padding', '5px 8px')
    await expect(searchRow).toHaveCSS('gap', '6px')
    await expect(search).toHaveCSS('font-size', '13px')
    await expect(search).toHaveCSS('font-weight', '430')
    await expect(search).toHaveCSS('border-bottom-width', '0px')
    const magnifier = searchRow.locator('[data-hcv-draft-icon="activitySearch"]')
    await expect(magnifier).toHaveCSS('width', '16px')
    await expect(magnifier).toHaveCSS('height', '16px')
    await expect(magnifier).not.toHaveCSS('mask-image', 'none')
    const dividers = menu.getByRole('separator')
    await expect(dividers).toHaveCount(2)
    await expect(dividers.first()).toHaveCSS('height', '1px')
    await expect(dividers.first()).toHaveCSS('margin', '4px 8px')
    const result = menu.getByRole('button', { name: 'Сайт', exact: true })
    await result.hover()
    await expect(result).toHaveCSS('background-color', /^rgba\(255, 255, 255, 0\.0(?:78|8)\)$/)
    await screenshot('project-menu-hover.png')
  }
  await search.fill('несуществующий-проект')
  await expect(menu.getByText('Проекты не найдены', { exact: true })).toBeVisible()
  await search.fill('Дизайн')
  await expect(menu.getByRole('button', { name: 'Дизайн', exact: true })).toBeVisible()
  await expect(menu.getByRole('button', { name: 'Сайт', exact: true })).toHaveCount(0)
  await search.press('Escape')
  if (before && await menu.count()) {
    seen.composer.filledEscapeClosed = false
    await project.click()
  }
  await expect(menu).toHaveCount(0)
  await expect(project).toBeFocused()
  if (!before) {
    const summary = page.locator('[data-hcv-context-card]')
    await summary.getByRole('button', { name: 'Действия со сводкой', exact: true }).click()
    await page.getByRole('menuitem', { name: 'Открепить сводку' }).click()
    await expect(summary).toHaveAttribute('data-pinned', 'false')
    await project.press('Enter')
    await expect(search).toBeFocused()
    await search.press('ArrowDown')
    await expect(menu.getByRole('button', { name: 'Тестовый проект', exact: true })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(project).toBeFocused()
    await expect(summary).toBeVisible()

    const input = composer.locator('[data-slot="composer-rich-input"][contenteditable="true"]')
    await input.fill('/')
    const drawer = page.locator('[data-slot="composer-completion-drawer"][role="listbox"]:visible')
    await expect(drawer.locator('button').first()).toBeVisible()
    const width = await drawer.evaluate(node => getComputedStyle(node).width)
    await input.fill('/hcv-no-such-command')
    await expect(drawer).toBeVisible()
    await expect(drawer.locator('button')).toHaveCount(0)
    await expect(drawer).toHaveCSS('width', width)
    await expect(drawer).toHaveCSS('border-radius', '20px')
    await screenshot('composer-no-command.png')
    await input.press('Escape')
    await input.fill('')
  }

  await go('profiles')
  const profiles = page.locator('[data-overlay-surface]:visible')
  const profileSearch = profiles.getByRole('textbox', { name: /Поиск профилей|Search profiles/ })
  const otherProfile = profiles.locator(`[data-panel-row="${profileName}"] > button[data-slot="row-button"]`)
  await expect(otherProfile).toBeVisible()
  await profileSearch.fill('нет такого профиля')
  await expect(otherProfile).toHaveCount(0)
  await profileSearch.fill('visual-audit')
  await otherProfile.press('Enter')
  const editor = profiles.locator('.cm-content[contenteditable="true"]')
  const editorRoot = profiles.locator('.cm-editor')
  const frame = profiles.locator('section > .min-h-48 > div:has(.cm-editor)')
  await expect(editor).toContainText('Тестовый профиль')
  await expect(editor).toBeFocused()
  if (!before) {
    await expect(frame).toHaveCSS('border-radius', '10px')
    await expect(frame).toHaveCSS('height', '320px')
    await expect(editorRoot).toHaveCSS('outline-style', 'none')
    await expect(editor).toHaveCSS('font-family', /Segoe UI/)
    await expect(profileSearch.locator('xpath=..')).toHaveCSS('border-radius', '999px')
  }
  seen.profiles = { frame: await paint(frame), editor: await paint(editorRoot), text: await paint(editor), row: await paint(otherProfile) }
  await screenshot('profiles-dark.png')
  if (!before) {
    const save = profiles.getByRole('button', { name: /Сохранить|Save/i }).last()
    await expect(save).toBeDisabled()
    await expect(save).toBeInViewport()
    await editor.press('Control+End')
    await editor.press('End')
    await page.keyboard.insertText('Проверено в тестовом профиле.')
    await expect(save).toBeEnabled()
    await editor.press('Control+s')
    await expect(save).toBeDisabled()
    await go('')
    await go('profiles')
    await otherProfile.click()
    await expect(editor).toContainText('Тестовый профиль')
    await editor.press('Control+End')
    await expect(editor).toContainText('Проверено в тестовом профиле.')

    await page.emulateMedia({ forcedColors: 'active' })
    await expect(editorRoot).toHaveCSS('outline-style', 'dotted')
    await expect(otherProfile.locator('xpath=..')).toHaveCSS('outline-style', 'solid')
    await screenshot('profiles-forced-colors.png')
    await page.emulateMedia({ forcedColors: 'none' })

    await go('')
    await openThemeSettings()
    await page.getByText(/^(Светлая|Light)$/, { exact: true }).first().click()
    await expect(page.locator('html')).toHaveAttribute('data-hermes-mode', 'light')
    await closeSettings()
    await page.setViewportSize({ width: 760, height: 720 })
    await go('profiles')
    await otherProfile.click()
    await expect(frame).toHaveCSS('border-radius', '10px')
    await expect(save).toBeInViewport()
    await screenshot('profiles-light-narrow.png')
    await go('settings?tab=gateway&page=connection')
    await expect(cards).toHaveCount(4)
    await expect(settings.locator('[aria-current="page"]')).toBeVisible()
    await expect.poll(() => settings.evaluate(node => node.scrollWidth <= node.clientWidth + 1)).toBe(true)
    await screenshot('gateway-light-narrow.png')
    await go('')
    await navigation('new-session').click()
    await expect(composer).toHaveCSS('background-color', 'rgb(245, 245, 245)')
    await project.click()
    await expect(search).toBeFocused()
    await expect(menu.getByRole('button', { name: 'Сайт', exact: true })).toBeVisible()
    await expect(menu).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await expect(menu).toHaveCSS('backdrop-filter', 'none')
    await expect(searchRow).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
    await expect(search).toHaveCSS('color', 'rgb(26, 28, 31)')
    await screenshot('project-menu-light-narrow.png')
    await page.emulateMedia({ forcedColors: 'active' })
    await expect(draft).toHaveCount(0)
    await expect(composer).toHaveCSS('border-top-width', '1px')
    await expect(composer.locator('[data-slot="composer-rich-input"]')).toBeEditable()
  }
  console.log(JSON.stringify({ visualParity: seen }))
}
