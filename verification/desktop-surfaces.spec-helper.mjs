export async function verifyDesktopSurfaces({ page, expect, screenshot, navigation }) {
  const baseline = process.env.HERMES_VISUAL_AUDIT_BASELINE === '1'
  const pageShell = page.locator('section.h-full.min-w-0.overflow-hidden:not([data-chat-surface]):visible').last()
  const search = pageShell.locator('input[placeholder]').first()
  const overlay = page.locator('[data-overlay-surface]:visible').last()
  const filters = pageShell.locator('[data-catalog-filters]')
  const filterMode = filters.locator('.catalog-filter-row > .inline-grid')
  const chips = filters.locator('.catalog-filter-chips')
  const searchBox = field => field.locator('..')
  const metrics = {}
  const corners = await page.locator('style[data-hcv-desktop-corners]').count() > 0
  const size = locator => locator.evaluate(node => {
    const css = getComputedStyle(node)
    return { height: node.getBoundingClientRect().height, radius: css.borderRadius, background: css.backgroundColor }
  })
  const go = async route => {
    await page.evaluate(path => { location.hash = '#/' + path }, route)
    await expect(page.locator('html')).toHaveAttribute('data-hcv-screen', route.split('?')[0])
  }

  await go('settings')
  const appearance = overlay.locator('[data-tour="nav-config:appearance"]')
  await appearance.click()
  const settingsTab = () => page.evaluate(() => new URL(location.hash.slice(1), 'https://fixture.invalid').searchParams.get('tab'))
  await expect.poll(settingsTab).toBe('config:appearance')
  const settingsSearch = overlay.locator('button[data-glass-opaque]:has(> svg.tabler-icon-search)')
  metrics.settingsSearch = await size(settingsSearch)
  await page.mouse.move(700, 110)
  await screenshot('settings-appearance.png')
  if (!baseline) await expect(settingsSearch).toHaveCSS('border-radius', '999px')
  await settingsSearch.press('Enter')
  await expect(page.locator('[data-slot="command-input"]:visible')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(settingsSearch).toBeVisible()
  const gateway = overlay.locator('[data-tour="nav-gateway"]')
  await gateway.click()
  await expect.poll(settingsTab).toBe('gateway')
  await screenshot('settings-gateway.png')
  await page.keyboard.press('Escape')

  await go('capabilities?tab=skills')
  await expect(pageShell.locator('[data-tour="tab-skills"]')).toHaveAttribute('data-active', 'true')
  await expect(search).toBeVisible()
  metrics.catalogSearch = await size(searchBox(search))
  if (!baseline) {
    await expect(filterMode).toHaveCSS('border-radius', '999px')
    const source = filterMode.getByRole('button', { name: 'Источник' })
    await source.hover()
    await expect(source).not.toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
    await source.click()
    await expect(source).toHaveAttribute('aria-pressed', 'true')
    await expect(source).toHaveCSS('border-radius', '999px')
    await expect(chips.getByRole('button', { name: 'Все', exact: true })).toHaveCSS('border-radius', '999px')
    await filterMode.getByRole('button', { name: 'Категория' }).click()
  }
  await screenshot('capabilities-skills.png')
  await go('capabilities?tab=plugins')
  await expect(pageShell.locator('[data-tour="tab-plugins"]')).toHaveAttribute('data-active', 'true')
  await expect(search).toBeVisible()
  await screenshot('capabilities-plugins.png')
  if (!baseline) {
    const rescan = pageShell.getByRole('button', { name: 'Пересканировать', exact: true })
    await rescan.hover()
    await expect(rescan).not.toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
    await rescan.click()
    await expect(page.getByText('Запущено сканирование плагинов', { exact: true })).toBeVisible()
    await screenshot('capabilities-plugin-rescan.png')
  }

  await navigation('artifacts').click()
  const table = pageShell.locator('table')
  const rows = table.locator('tbody tr')
  await expect(rows.first()).toBeVisible({ timeout: 15000 })
  metrics.artifactsSearch = await size(searchBox(search))
  metrics.artifactRow = await size(rows.first())
  if (!baseline) {
    const icon = rows.first().locator('td:first-child > :is(a, button) > span:first-child')
    await expect(icon).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
    await expect(icon).toHaveCSS('border-top-width', '0px')
  }
  await screenshot('artifacts.png')
  await pageShell.locator('[data-tour="tab-link"]').click()
  await expect(pageShell.locator('[data-tour="tab-link"]')).toHaveAttribute('data-active', 'true')
  await expect(rows.getByText(/Справка по каталогу|connector guide/i)).toBeVisible()
  await search.fill('definitely-no-artifact-8e7f')
  await expect(table).toHaveCount(0)
  await search.clear()
  await expect(rows.first()).toBeVisible()
  await rows.first().hover()
  await screenshot('artifacts-hover.png')
  if (!baseline) {
    await expect(searchBox(search)).toHaveCSS('border-radius', '9999px')
    await expect(rows.first()).toHaveCSS('height', '48px')
  }
  await pageShell.locator('[data-tour="tab-all"]').click()
  await expect(pageShell.locator('[data-tour="tab-all"]')).toHaveAttribute('data-active', 'true')

  await navigation('cron').click()
  const cronSearch = overlay.locator('input[placeholder]').first()
  const job = overlay.locator('[data-panel-row]').filter({ hasText: 'Проверка Cron в боковой панели' })
  await expect(job).toBeVisible({ timeout: 15000 })
  metrics.cronSearch = await size(searchBox(cronSearch))
  await cronSearch.fill('нет-тестовой-задачи-85e')
  await expect(job).toHaveCount(0)
  await cronSearch.clear()
  await job.locator('button').first().click()
  await expect(overlay.locator('h3').filter({ hasText: 'Проверка Cron в боковой панели' })).toBeVisible()
  if (corners) {
    await expect(overlay.locator('section > pre.rounded[class~="bg-foreground/5"]')).toHaveCSS('border-radius', '10px')
  }
  await screenshot('scheduled.png')
  await page.keyboard.press('Escape')

  const row = page.locator('[data-sessions-project]:not([data-sessions-mode])').filter({ hasText: 'Тестовый проект' }).first()
  await row.locator('[data-hcv-project-name]').hover()
  const preview = page.locator('[data-hcv-project-preview]')
  await expect(preview).toBeVisible()
  await expect(preview.getByRole('button')).toBeVisible()
  await screenshot('project-preview.png')
  const actions = row.getByRole('button', { name: 'Действия', exact: true })
  await actions.click()
  const rename = page.getByRole('menuitem').filter({ hasText: /^Переименовать/ }).first()
  await expect(rename).toBeVisible()
  await screenshot('project-actions.png')
  await rename.click()
  const dialog = page.getByRole('dialog').filter({ has: page.locator('input') }).last()
  const name = dialog.locator('input').first()
  await expect(name).toBeFocused()
  await expect(name).toHaveValue('Тестовый проект')
  await screenshot('project-rename.png')
  await name.fill('Проект после переименования')
  await name.press('Enter')
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('[data-hcv-project-name]').filter({ hasText: 'Проект после переименования' })).toBeVisible()

  await navigation('messaging').click()
  const platforms = pageShell.locator('aside li > button:visible')
  const telegram = platforms.filter({ hasText: /Telegram/i }).first()
  await expect(telegram).toBeVisible({ timeout: 30000 })
  metrics.messagingSearch = await size(searchBox(search))
  await search.fill('Telegram')
  await expect(telegram).toBeVisible()
  await expect(platforms.filter({ hasNotText: /Telegram/i })).toHaveCount(0)
  await telegram.click()
  await expect(pageShell.locator('main h3').first()).toHaveText('Telegram')
  if (corners) {
    const setup = pageShell.locator('main section > .mt-3 > div.rounded-xl.border[class~="bg-(--ui-surface-secondary,transparent)"]')
    await expect(setup.first()).toHaveCSS('border-radius', '12px')
  }
  await search.clear()
  await screenshot('messaging.png')

  await page.setViewportSize({ width: 800, height: 670 })
  await navigation('artifacts').click()
  await expect(table).toBeVisible()
  await expect(pageShell.locator('[data-tour="tab-all"]')).toBeVisible()
  await screenshot('artifacts-narrow.png')
  console.log('Desktop surface metrics', JSON.stringify(metrics))
}
