import assert from 'node:assert/strict'

export async function verifyChatActivity({ page, app, expect, projectChat, screenshot, openThemeSettings, closeSettings, themeCard }) {
  const chat = page.locator('[data-chat-surface][data-session-anchor="workspace"]:visible')
  const root = page.locator('html')
  const tool = (icon) => chat.locator(`[data-tool-row][data-hcv-activity-icon="${icon}"]`)
  const toggle = (row) => row.locator(':scope > div:first-child button[aria-expanded]')
  const capture = process.env.HERMES_VISUAL_SKIP_SCREENSHOTS !== '1'
  const auditBaseline = process.env.HERMES_VISUAL_AUDIT_BASELINE === '1'
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await projectChat('Проверка каталога').click()
  await expect(chat.getByText('Проверка истории завершена.', { exact: true })).toBeVisible()
  const transcript = chat.locator('[data-slot="aui_thread-content"]')
  const width = (await transcript.boundingBox()).width
  const steps = chat.getByRole('button', { name: /^(Шаги работы|Work steps)$/ })
  await steps.click()
  const group = chat.locator('[data-tool-group] > [data-tool-summary]').filter({ hasText: /fixture-note/ })
  const groupButton = group.locator('button[aria-expanded]')
  await expect(group).toHaveAttribute('data-hcv-activity-icon', 'activityRead')
  await expect(groupButton).toHaveAttribute('aria-expanded', 'false')
  await groupButton.click()
  await expect(groupButton).toHaveAttribute('aria-expanded', 'true')
  const read = tool('activityRead')
  const terminal = tool('activityTerminal')
  const image = tool('activityImage')
  await expect(read).toBeVisible()
  await expect(terminal).toBeVisible()
  await expect(image).toBeVisible()
  await expect(read).toHaveCSS('font-size', '14px')
  await expect(read.locator(':scope > div:first-child span.self-center > svg')).toHaveCSS('width', '16px')
  await expect(read.locator(':scope > div:first-child span.self-center > svg')).toHaveCSS('mask-image', /^url\(/)
  await toggle(read).click()
  await expect(read).toHaveCSS('border-top-width', '0px')
  const content = read.locator('pre').filter({ hasText: 'Содержимое файла из сохранённой истории' })
  await expect(content).toBeVisible()
  await expect(content).toHaveCSS('font-size', '12px')
  await app.evaluate(({ clipboard }) => {
    clipboard.writeText = (text) => { globalThis.hcvCopiedToolOutput = text }
  })
  const copyOutput = read.getByRole('button', { name: /Копировать|Copy/ })
  await toggle(read).hover()
  if (!auditBaseline) {
    await expect(copyOutput).toHaveCSS('opacity', '0')
    await expect(copyOutput).toHaveCSS('transition-duration', '0.15s')
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await expect(copyOutput).toHaveCSS('transition-property', 'none')
    await page.emulateMedia({ reducedMotion: 'no-preference' })
  }
  await content.hover()
  await expect(copyOutput).toHaveCSS('opacity', '1')
  await copyOutput.click()
  await expect.poll(() => app.evaluate(() => globalThis.hcvCopiedToolOutput)).toContain('Содержимое файла из сохранённой истории')
  await toggle(terminal).click()
  await expect(terminal.locator('code').filter({ hasText: 'echo fixture-activity-command' })).toBeVisible()
  await expect(terminal.locator('pre').filter({ hasText: 'fixture-activity-output' })).toBeVisible()
  const badge = await terminal.getByText('exit 0', { exact: true }).boundingBox()
  const terminalCopy = await terminal.getByRole('button', { name: /Копировать|Copy/ }).boundingBox()
  assert(badge && terminalCopy && badge.x + badge.width <= terminalCopy.x)
  await toggle(image).click()
  const thumbnail = image.locator('[data-slot="aui_markdown-image"]')
  const picture = thumbnail.locator('img')
  await expect(picture).toBeVisible()
  await expect.poll(() => picture.evaluate(img => img.naturalWidth)).toBe(160)
  await expect(thumbnail).toHaveCSS('width', '80px')
  await expect(thumbnail).toHaveCSS('height', '80px')
  await expect(thumbnail.getByRole('button', { name: /Скачать изображение|Download image/ })).toHaveCSS('width', '24px')
  await picture.click()
  await expect(page.getByRole('dialog').locator('img')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  assert.equal((await transcript.boundingBox()).width, width)
  if (capture) await screenshot('activity-dark.png')

  await openThemeSettings()
  await page.getByText(/^(Светлая|Light)$/).first().click()
  await expect(root).toHaveAttribute('data-hermes-mode', 'light')
  await closeSettings()
  if (await steps.getAttribute('aria-expanded') !== 'true') await steps.click()
  await expect(content).toBeVisible()
  await expect(thumbnail).toHaveCSS('width', '80px')
  if (capture) await screenshot('activity-light.png')
  await groupButton.click()
  await expect(groupButton).toHaveAttribute('aria-expanded', 'false')
  await expect(content).toBeHidden()
  await expect(picture).toBeVisible()
  await openThemeSettings()
  await themeCard('Nous').click()
  await closeSettings()
  await expect(root).not.toHaveAttribute('data-hermes-theme', 'codex-workspace')
  await expect.poll(() => chat.evaluate(node => getComputedStyle(node).getPropertyValue('--hcv-activity-font').trim())).toBe('')
  console.log(JSON.stringify({ storedToolHistory: true, fileCopy: true, terminalOutput: true, imagePreview: true, chatWidthUnchanged: true, lightAndDark: true, themeScoped: true }))
}
