import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'

export async function verifyChatApproval({ page, expect, projectChat, projectFolder, screenshot,
  openThemeSettings, closeSettings, themeCard }) {
  await projectChat('Ревью интерфейса').click()
  const chat = page.locator('[data-chat-surface][data-composer-target="main"]:visible')
  const composer = chat.locator('[data-slot="composer-rich-input"]')
  const metrics = page.getByRole('button', { name: 'Нет, спасибо', exact: true })
  if (await metrics.isVisible()) await metrics.click()
  const ask = async prompt => {
    await composer.fill(prompt)
    await composer.press('Enter')
    const card = chat.locator('[data-slot="tool-approval-card"]:visible')
    await expect(card).toHaveCount(1, { timeout: 120000 })
    await expect(card.locator('[data-hcv-approval-part="files"]')).toBeVisible({ timeout: 30000 })
    return card
  }
  const agents = path.join(projectFolder, 'AGENTS.md')
  const note = path.join(projectFolder, 'fixture-note.md')
  let card = await ask('Тест разрешения: несколько файлов')
  await expect(card.getByText('Согласовать правила и примечание', { exact: false })).toBeVisible()
  await expect(card.locator('[data-hcv-approval-part="file"]')).toHaveCount(2)
  await expect(card).toContainText('AGENTS.md')
  await expect(card).toContainText('fixture-note.md')
  await expect(card).toContainText('-Исходное правило.')
  await expect(card).toContainText('+Новое правило.')
  await expect(card).toContainText('+Новое примечание.')
  await expect(card.getByRole('button', { name: 'Разрешить', exact: true })).toBeEnabled()
  if (await metrics.isVisible()) await metrics.click()
  await page.mouse.move(1100, 700)
  await screenshot('approval-core-multifile.png')
  await page.setViewportSize({ width: 760, height: 840 })
  assert.equal(await card.evaluate(element => element.scrollWidth > element.clientWidth), false)
  await expect(card.getByRole('button', { name: 'Разрешить', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 920 })
  await page.emulateMedia({ forcedColors: 'active' })
  await expect(card.locator('[data-hcv-approval-part="files"]')).toBeVisible()
  await page.emulateMedia({ forcedColors: 'none' })
  await openThemeSettings()
  await themeCard('Nous').click()
  await closeSettings()
  await expect(card.locator('[data-hcv-approval-part="files"]')).toBeVisible()
  await expect(card.getByRole('button', { name: 'Разрешить', exact: true })).toBeEnabled()
  await screenshot('approval-core-nous.png')
  await openThemeSettings()
  await themeCard('Codex').click()
  await closeSettings()
  await expect(card.locator('[data-hcv-approval-part="files"]')).toBeVisible()
  assert.equal(fs.readFileSync(agents, 'utf8'), 'Исходное правило.\n')
  assert.match(fs.readFileSync(note, 'utf8'), /Изменение для проверки/)
  await card.locator('[data-approval-deny]').click()
  await expect(card).toHaveCount(0, { timeout: 30000 })
  assert.equal(fs.readFileSync(agents, 'utf8'), 'Исходное правило.\n')
  assert.match(fs.readFileSync(note, 'utf8'), /Изменение для проверки/)
  await expect(composer).toBeEnabled({ timeout: 30000 })

  await composer.fill('Тест разрешения: одинаковые имена')
  await composer.press('Enter')
  const queued = chat.locator('[data-slot="card-stack-front"][data-stack-active="true"] [data-slot="tool-approval-card"]:visible')
  await expect(queued).toHaveCount(1, { timeout: 120000 })
  await expect(queued.locator('[data-hcv-approval-part="files"]')).toBeVisible({ timeout: 30000 })
  const firstId = await queued.getAttribute('data-request-id')
  const firstPath = await queued.locator('[data-hcv-approval-part="path"]').textContent()
  const firstText = await queued.locator('[data-hcv-approval-part="reason"]').textContent()
  await queued.locator('[data-approval-deny]').click()
  await expect.poll(async () => queued.evaluateAll(nodes => nodes[0]?.getAttribute('data-request-id') ?? null),
    { timeout: 30000 }).not.toBe(firstId)
  await expect(queued.locator('[data-hcv-approval-part="files"]')).toBeVisible({ timeout: 30000 })
  const secondPath = await queued.locator('[data-hcv-approval-part="path"]').textContent()
  const secondText = await queued.locator('[data-hcv-approval-part="reason"]').textContent()
  assert.notEqual(firstPath, secondPath)
  assert.notEqual(firstText, secondText)
  assert.match([firstText, secondText].join(' '), /Причина первого файла/)
  assert.match([firstText, secondText].join(' '), /Причина второго файла/)
  await queued.locator('[data-approval-deny]').click()
  await expect(queued).toHaveCount(0, { timeout: 30000 })
  assert.equal(fs.readFileSync(agents, 'utf8'), 'Исходное правило.\n')
  assert.equal(fs.readFileSync(path.join(projectFolder, 'nested', 'AGENTS.md'), 'utf8'), 'Вложенное правило.\n')

  await expect(composer).toBeEnabled({ timeout: 30000 })
  card = await ask('Тест разрешения: несколько файлов')
  await expect(card.getByRole('button', { name: 'Разрешить', exact: true })).toBeEnabled()
  await card.getByRole('button', { name: 'Разрешить', exact: true }).click()
  await expect.poll(() => fs.readFileSync(agents, 'utf8'), { timeout: 30000 }).toBe('Новое правило.\n')
  await expect.poll(() => fs.readFileSync(note, 'utf8'), { timeout: 30000 }).toContain('Новое примечание.')
  await expect(composer).toBeEnabled({ timeout: 30000 })
  const mode = chat.locator('[data-hcv-approval]')
  await mode.click()
  await page.locator('[data-hcv-approval-menu]').getByRole('menuitemradio', { name: /^Ручной/ }).click()
  await composer.fill('Тест разрешения: обычная команда')
  await composer.press('Enter')
  const command = chat.locator('[data-slot="tool-approval-card"]:visible')
  await expect(command).toHaveCount(1, { timeout: 120000 })
  await expect(command).not.toHaveAttribute('data-hcv-protected-approval', '')
  await command.locator('[data-approval-deny]').click()
  await expect(command).toHaveCount(0, { timeout: 30000 })
  assert(fs.existsSync(path.join(projectFolder, 'approval-victim')))
  return { multifile: true, concurrentSameBasename: true, denial: true, approval: true,
    nous: true, forcedColors: true, narrow: true, command: true }
}
