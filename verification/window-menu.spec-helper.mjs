import assert from 'node:assert/strict'

export async function verifyWindowMenu({ page, expect, screenshot, openThemeSettings, closeSettings }) {
  const nav = page.locator('[data-hcv-window-menu]')
  const trigger = (name) => nav.getByRole('button', { name, exact: true })
  const popup = page.locator('[data-hcv-window-menu-content][data-state="open"]')
  const item = (name) => popup.getByRole('menuitem', { name, exact: true })
  const capture = process.env.HERMES_VISUAL_SKIP_SCREENSHOTS !== '1'
  const shot = async (name) => {
    if (capture) await screenshot(name, { clip: { x: 0, y: 0, width: 560, height: 220 } })
  }
  const file = trigger('Файл')
  const dragZone = page.locator('[data-window-drag-handle]:visible').first()
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await file.hover()
  await expect(file).toHaveAttribute('aria-expanded', 'false')
  await expect(popup).toHaveCount(0)
  await expect(file).toHaveCSS('height', '24px')
  await expect(file).toHaveCSS('font-size', '14px')
  await expect(file).toHaveCSS('padding-inline-start', '10px')
  await expect(dragZone).toHaveCSS('-webkit-app-region', 'drag')

  await file.click()
  await expect(popup).toHaveAttribute('data-hcv-window-menu-content', 'file')
  await expect(dragZone).toHaveCSS('-webkit-app-region', 'no-drag')
  await expect(popup).toHaveCSS('background-color', 'rgb(31, 31, 31)')
  await expect(popup).toHaveCSS('border-top-width', '0px')
  await expect(popup).toHaveCSS('border-radius', /^(6|7\.5)px$/)
  await expect(popup).toHaveCSS('animation-name', 'none')
  await expect(popup).toHaveCSS('padding-top', '4px')
  await expect(popup).toHaveCSS('box-shadow', 'rgba(0, 0, 0, 0.42) 0px 4px 12px 0px')
  const anchor = await file.boundingBox()
  const panel = await popup.boundingBox()
  assert(anchor && panel && Math.abs(anchor.x - panel.x) < 1 && Math.abs(anchor.y + anchor.height - panel.y) < 1)
  assert.equal(panel.width, 220)
  const newChat = item('Новый чат')
  await expect(newChat).toHaveCSS('height', '28px')
  await expect(newChat).toHaveCSS('padding-inline-start', '16px')
  await expect(newChat).toHaveCSS('font-size', '12px')
  await expect(newChat).toHaveCSS('line-height', '18px')
  await expect(newChat.locator('[data-hcv-window-menu-shortcut]')).toHaveText('Ctrl+N')
  await expect(popup.getByRole('separator')).toHaveCSS('height', '0.5px')
  await expect(popup.getByRole('separator')).toHaveCSS('margin-top', '8px')
  await shot('window-menu-file.png')
  await newChat.hover()
  await expect(newChat).toHaveCSS('background-color', /^rgba\(255, 255, 255, 0\.0(?:78|8)\)$/)
  await shot('window-menu-hover.png')

  const glideTo = async (name) => {
    const button = await trigger(name).boundingBox()
    assert(button)
    await page.mouse.move(button.x + button.width / 2, button.y + button.height / 2, { steps: 12 })
  }
  await glideTo('Правка')
  await expect(popup).toHaveCount(1)
  await expect(item('Отменить ввод')).toBeVisible()
  await glideTo('Вид')
  await expect(popup).toHaveCount(1)
  await expect(item('Боты')).toBeVisible()
  await expect(popup).toHaveCSS('width', '300px')
  await shot('window-menu-view.png')
  await glideTo('Справка')
  await expect(popup).toHaveCount(1)
  await expect(item('О программе')).toBeVisible()
  await page.mouse.move(700, 18, { steps: 20 })
  await expect(item('О программе')).toBeVisible()
  await page.mouse.move(700, 140, { steps: 20 })
  await expect(item('О программе')).toBeVisible()
  await glideTo('Справка')
  await glideTo('Вид')
  await expect(item('Боты')).toBeVisible()
  await page.mouse.move(700, 140, { steps: 20 })
  await expect(item('Боты')).toBeVisible()
  await page.mouse.click(700, 140)
  await expect(popup).toHaveCount(0)
  await expect(dragZone).toHaveCSS('-webkit-app-region', 'drag')
  await glideTo('Правка')
  await expect(popup).toHaveCount(0)
  await file.click()
  await dragZone.hover()
  await expect(popup).toHaveAttribute('data-hcv-window-menu-content', 'file')
  await dragZone.click()
  await expect(popup).toHaveCount(0)

  const edit = trigger('Правка')
  await edit.press('Enter')
  await expect(item('Отменить ввод')).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(item('Повторить ввод')).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(item('Сеансы')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(popup).toHaveCount(0)
  await expect(trigger('Вид')).toBeFocused()
  await file.click()
  await expect(popup).toHaveCount(1)
  await file.click()
  await expect(popup).toHaveCount(0)

  await openThemeSettings()
  await page.getByText(/^(Светлая|Light)$/).first().click()
  await expect(page.locator('html')).toHaveAttribute('data-hermes-mode', 'light')
  await closeSettings()
  await file.click()
  await expect(popup).toHaveCSS('background-color', 'rgb(248, 248, 249)')
  await shot('window-menu-light.png')
  await trigger('Справка').hover()
  await item('О программе').click()
  await expect(page).toHaveURL(/\/settings\?tab=about/)
  console.log(JSON.stringify({ anchor, panel, fourMenus: true, hover: true, keyboard: true, nativeAction: true, lightAndDark: true }))
}
