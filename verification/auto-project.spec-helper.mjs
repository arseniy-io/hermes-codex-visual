export async function verifyAutoProject({ page, expect, screenshot }) {
  const tree = page.locator('[data-sessions-mode="projects"]')
  const item = tree.locator('[data-sessions-project]').filter({ hasText: 'auto-workspace' }).first()
  await expect(item).toBeVisible()
  const native = item.locator('button[data-hcv-native-project-action]').filter({ hasText: 'auto-workspace' })
  if (process.env.HERMES_VISUAL_AUTO_BEFORE === '1') {
    await screenshot('auto-project-before.png')
    console.log('Before:', await item.evaluate(node => node.outerHTML))
    return
  }
  const name = item.locator('[data-hcv-project-name]')
  const row = item.locator('[data-hcv-project-row]')
  const ordinary = tree.locator('[data-hcv-project-name]').filter({ hasText: 'Тестовый проект' }).first()
  await expect(name).toBeVisible()
  await expect(native).toBeHidden()
  await expect(name).toHaveCSS('color', await ordinary.evaluate(node => getComputedStyle(node).color))
  await expect(name).toHaveCSS('font-size', '14px')
  await expect(name).toHaveCSS('opacity', '1')
  await expect(row.locator('.codicon-chevron-right')).toBeHidden()
  await name.hover()
  await expect(row).toHaveCSS('background-color', 'rgb(41, 41, 41)')
  await screenshot('auto-project-hover.png')
  if (await name.getAttribute('aria-expanded') === 'true') {
    await name.click()
    await expect(name).toHaveAttribute('aria-expanded', 'false')
    await expect(item.getByText('Чат автоматического проекта')).toHaveCount(0)
  }
  await name.click()
  await expect(name).toHaveAttribute('aria-expanded', 'true')
  const chat = item.getByRole('button', { name: 'Чат автоматического проекта', exact: true })
  await expect(chat).toBeVisible()
  await name.click()
  await name.click()
  await expect(name).toHaveAttribute('aria-expanded', 'true')
  await expect(chat).toBeVisible()
  await name.press('Space')
  await expect(name).toHaveAttribute('aria-expanded', 'false')
  await expect(chat).toHaveCount(0)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await name.press('Enter')
  await expect(chat).toBeVisible()
  await chat.click()
  await expect(page.locator('[data-slot="aui_thread-viewport"]').getByText('Тестовый ответ.', { exact: true })).toBeVisible()
  console.log('Auto project: styling, hover, repeat click, keyboard, reduced motion and chat opening passed')
}
